'use strict';

/**
 * מספרים במילים — משותף לכל מחוללי התוכן המספריים.
 *
 * למה זה קובץ בפני עצמו: חשבון, ספרות רומיות, גימטריה, ספירת עצמים וקוביות
 * כולם עונים במספר, וכולם צריכים בדיוק את אותן צורות דיבור. סט כללים אחד
 * מונע מצב שבו "ארבעים ואחת" מתקבלת בקטגוריה אחת ונדחית בשנייה.
 */

// נקבה — צורת הספירה המופשטת, וזו שאומרים כשעונים "כמה יוצא".
const ONES_F = ['אפס', 'אחת', 'שתיים', 'שלוש', 'ארבע', 'חמש', 'שש', 'שבע', 'שמונה', 'תשע'];
const TEENS_F = ['עשר', 'אחת עשרה', 'שתים עשרה', 'שלוש עשרה', 'ארבע עשרה', 'חמש עשרה',
  'שש עשרה', 'שבע עשרה', 'שמונה עשרה', 'תשע עשרה'];

// זכר — מה שאומרים כשמונים עצמים: "שבעה עיגולים", "חמישה כוכבים".
const ONES_M = ['אפס', 'אחד', 'שניים', 'שלושה', 'ארבעה', 'חמישה', 'שישה', 'שבעה', 'שמונה', 'תשעה'];
const TEENS_M = ['עשרה', 'אחד עשר', 'שנים עשר', 'שלושה עשר', 'ארבעה עשר', 'חמישה עשר',
  'שישה עשר', 'שבעה עשר', 'שמונה עשר', 'תשעה עשר'];

const TENS = ['', '', 'עשרים', 'שלושים', 'ארבעים', 'חמישים', 'שישים', 'שבעים', 'שמונים', 'תשעים'];
const HUNDREDS = ['', 'מאה', 'מאתיים', 'שלוש מאות', 'ארבע מאות', 'חמש מאות',
  'שש מאות', 'שבע מאות', 'שמונה מאות', 'תשע מאות'];
const THOUSANDS = ['', 'אלף', 'אלפיים', 'שלושת אלפים', 'ארבעת אלפים', 'חמשת אלפים',
  'ששת אלפים', 'שבעת אלפים', 'שמונת אלפים', 'תשעת אלפים'];

/** מספר במילים, בצורה שבה אומרים אותו בקול. */
function numberWords(n, gender = 'f') {
  const ones = gender === 'm' ? ONES_M : ONES_F;
  const teens = gender === 'm' ? TEENS_M : TEENS_F;

  if (n >= 1000) {
    const rest = n % 1000;
    const head = THOUSANDS[Math.floor(n / 1000)];
    return rest ? `${head} ו${numberWords(rest, gender)}` : head;
  }
  const h = Math.floor(n / 100);
  const rest = n % 100;
  const head = HUNDREDS[h];
  if (!rest) return head || ones[0];
  // בעברית מדוברת יש ו' לפני היחידות: "ארבעים וארבע", לא "ארבעים ארבע"
  const tail = rest < 10 ? ones[rest]
    : rest < 20 ? teens[rest - 10]
      : rest % 10 === 0 ? TENS[Math.floor(rest / 10)]
        : `${TENS[Math.floor(rest / 10)]} ו${ones[rest % 10]}`;
  return head ? `${head} ו${tail}` : tail;
}

/**
 * הניסוחים הנוספים שסביר לשמוע לאותו מספר: בלי ו' החיבור, ובספרות.
 *
 * מין אחד בלבד, והוא של התשובה עצמה. הוספת שני המינים נשמעת נדיבה אבל
 * שוברת את המשחק: "עשרה" היא עשר בזכר, והיא גם הזנב של "אחת עשרה" — ומי
 * שרואה אחת עשרה ואומר אותה היה זוכה בנקודה על התמונה של עשר. בעברית
 * מדוברת אין דרך להבחין ביניהן, ולכן כל קטגוריה בוחרת מין ודבקה בו: ספירת
 * עצמים בזכר ("שבעה כוכבים"), וכל השאר בנקבה, שהיא צורת המספר המופשט.
 */
function numberAliases(n, gender = 'f') {
  const primary = numberWords(n, gender);
  const variants = new Set([String(n), primary.replace(/ ו/g, ' ')]);
  variants.delete(primary);
  return [...variants];
}

module.exports = { numberWords, numberAliases };

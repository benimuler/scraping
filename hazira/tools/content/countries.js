/** מצרף כל מדינה שיש לה גם מתאר במפה וגם שם עברי. */
function collect() {
  const byN3 = new Map(worldCountries.map((c) => [c.ccn3, c]));
  const shapes = feature(topo, topo.objects.countries).features;
  const out = [];
  for (const shape of shapes) {
    const meta = byN3.get(String(shape.id).padStart(3, '0'));
    if (!meta) continue;
    const he = HEBREW[meta.cca2];
    if (!he) continue;
    out.push({
      cca2: meta.cca2, shape, region: meta.region,
      name: he[0], capital: he[1], area: meta.area || 0,
    });
  }
  return out;
}

/** מתאר מדינה, מוטל ומותאם למסגרת — כך גם מדינה זעירה ממלאת את התמונה. */
function outlineSvg(shape) {
  const projection = geoMercator().fitExtent([[40, 40], [W - 40, H - 40]], shape);
  const d = geoPath(projection)(shape);
  return svg(
    `<path d="${d}" fill="#2b3454" stroke="#ffcc33" stroke-width="2.5" ` +
    `stroke-linejoin="round"/>`,
    { bg: '#101528' },
  );
}

/**
 * @returns {Array} קטגוריות: מתאר מדינה לפי יבשת, ובירות לפי יבשת.
 */
function build({ minItems = 10 } = {}) {
  const countries = collect();
  const byRegion = new Map();
  for (const c of countries) {
    if (!REGIONS[c.region]) continue;
    if (!byRegion.has(c.region)) byRegion.set(c.region, []);
    byRegion.get(c.region).push(c);
  }

  const categories = [];
  for (const [region, list] of byRegion) {
    if (list.length < minItems) continue;
    const { id, name } = REGIONS[region];

    // שטח הוא הקירוב הזמין הטוב ביותר ל"כמה המדינה מוכרת": רוסיה, ברזיל
    // וסין ראשונות; ג׳יבוטי וגמביה אחרונות. המיון יורד, והדרגה נגזרת ממנו.
    list.sort((a, b) => b.area - a.area);
    const level = (index) => Math.min(5, Math.floor((index / list.length) * 5) + 1);

    categories.push({
      id: `map-${id}`,
      name: `מפות ${name}`,
      hint: 'איזו מדינה?',
      items: list.map((c, i) => ({
        svg: outlineSvg(c.shape), answer: c.name, slug: c.cca2, difficulty: level(i),
      })),
    });

    categories.push({
      id: `capitals-${id}`,
      name: `בירות ${name}`,
      hint: 'של איזו מדינה?',
      items: list.map((c, i) => ({
        text: c.capital, answer: c.name, slug: c.cca2, difficulty: level(i),
      })),
    });
  }
  return categories;
}

module.exports = { build, HEBREW, collect };
